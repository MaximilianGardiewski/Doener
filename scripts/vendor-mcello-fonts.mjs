#!/usr/bin/env node
/*
 * Vendors the Mcello brand typefaces into the repository.
 *
 * Same reasoning as scripts/vendor-mcello-gsap.mjs and the same rule from D074:
 * no CDN at runtime. A Google Fonts <link> would make every page load depend on
 * a third party, leak visitor IPs to it, and break the offline app shell. So the
 * files are fetched once, pinned here, committed, and served from our origin.
 *
 * Latin subsets only, variable weights, woff2 only. Both families are OFL.
 *
 *   node scripts/vendor-mcello-fonts.mjs
 */
import { mkdir, writeFile, readFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outDir = path.join(root, "apps/mcello/public/vendor/fonts");

/*
 * Google serves woff2 only to a browser-shaped UA; a short one gets ttf, which
 * is roughly twice the bytes. Pinned Chrome UA rather than a moving target.
 */
const UA = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36";

export const MCELLO_FONTS = [
  {
    // Interface: numbers are the interface here, and Inter has real tabular
    // lining figures, which the price/quantity treatment depends on.
    family: "Inter",
    query: "Inter:wght@400..800",
    file: "inter-latin-variable.woff2",
  },
  {
    // Display: warm high-contrast old style. Keeps the serif role the previous
    // stack had, without the black-and-gold luxury register ART_DIRECTION.md
    // rules out.
    family: "Fraunces",
    query: "Fraunces:opsz,wght@9..144,400..800",
    file: "fraunces-latin-variable.woff2",
  },
];

async function css(query) {
  const url = `https://fonts.googleapis.com/css2?family=${query}&display=swap`;
  const response = await fetch(url, { headers: { "user-agent": UA } });
  if (!response.ok) throw new Error(`${url} -> HTTP ${response.status}`);
  return response.text();
}

/** Latin only: the other subsets are bytes no Mcello surface renders. */
function latinSource(sheet, family) {
  const blocks = sheet.split("@font-face").slice(1);
  for (const block of blocks) {
    if (!block.includes("/* latin */") && !/latin \*\//.test(block)) continue;
  }
  // The comment naming the subset precedes its @font-face block.
  const marked = sheet.split(/\/\*\s*([a-z-]+)\s*\*\//).slice(1);
  for (let i = 0; i < marked.length; i += 2) {
    if (marked[i] !== "latin") continue;
    const match = marked[i + 1].match(/url\((https:\/\/fonts\.gstatic\.com\/[^)]+\.woff2)\)/);
    if (match) return match[1];
  }
  throw new Error(`no latin woff2 found for ${family}`);
}

async function main() {
  await mkdir(outDir, { recursive: true });
  const manifest = [];

  for (const font of MCELLO_FONTS) {
    const sheet = await css(font.query);
    const source = latinSource(sheet, font.family);
    const response = await fetch(source, { headers: { "user-agent": UA } });
    if (!response.ok) throw new Error(`${source} -> HTTP ${response.status}`);
    const bytes = Buffer.from(await response.arrayBuffer());
    if (bytes.subarray(0, 4).toString("ascii") !== "wOF2") {
      throw new Error(`${font.family}: not a woff2 payload`);
    }
    await writeFile(path.join(outDir, font.file), bytes);
    manifest.push({ family: font.family, file: font.file, bytes: bytes.length, source });
    console.log(`${font.family.padEnd(10)} ${String(bytes.length).padStart(7)} bytes  ${font.file}`);
  }

  await writeFile(
    path.join(outDir, "MANIFEST.json"),
    `${JSON.stringify({ note: "Generated by scripts/vendor-mcello-fonts.mjs. Both families are OFL.", fonts: manifest }, null, 2)}\n`,
  );
  const total = manifest.reduce((sum, entry) => sum + entry.bytes, 0);
  console.log(`\ntotal ${total} bytes across ${manifest.length} files`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) await main();
